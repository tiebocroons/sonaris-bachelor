import { View, Text, StyleSheet, Pressable, ScrollView, Platform, Alert } from 'react-native';
import React, { useState } from 'react';
import { useRouter } from 'expo-router';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { NormalHearing } from '@/components/icons/NormalHearing';
import { SevereHearing } from '@/components/icons/SevereHearing';
import { getAnalysis, clearAnalysis, AnalysisData } from '@/constants/analysis-store';

function buildPdfHtml(analysis: AnalysisData, title: string): string {
  const date = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

  const thresholdsHtml = (() => {
    if (!analysis.thresholds) return '';
    const t = analysis.thresholds as { leftEar?: Record<string, number>; rightEar?: Record<string, number> };
    const freqs = ['250', '500', '1k', '2k', '4k', '8k'];
    const freqKeys = ['250', '500', '1000', '2000', '4000', '8000'];
    const headerCells = freqs.map(f => `<th>${f}</th>`).join('');
    const leftRow = t.leftEar
      ? `<tr><td class="ear">L</td>${freqKeys.map(f => `<td>${t.leftEar![f] ?? '—'}</td>`).join('')}</tr>`
      : '';
    const rightRow = t.rightEar
      ? `<tr class="alt"><td class="ear">R</td>${freqKeys.map(f => `<td>${t.rightEar![f] ?? '—'}</td>`).join('')}</tr>`
      : '';
    return `
      <h3>Thresholds (dB HL)</h3>
      <table>
        <thead><tr><th>Hz</th>${headerCells}</tr></thead>
        <tbody>${leftRow}${rightRow}</tbody>
      </table>`;
  })();

  const recsHtml = analysis.recommendations?.length
    ? `<h3>Recommendations</h3><ul>${analysis.recommendations.map((r: string) => `<li>${r}</li>`).join('')}</ul>`
    : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Sonaris — ${title}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: Arial, sans-serif; color: #222; padding: 40px 50px; }
    header { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 3px solid #E31937; padding-bottom: 12px; margin-bottom: 28px; }
    header h1 { font-size: 28px; color: #E31937; letter-spacing: 1px; }
    header span { font-size: 13px; color: #666; }
    h2 { font-size: 22px; margin-bottom: 14px; color: #111; }
    h3 { font-size: 15px; font-weight: bold; color: #E31937; margin: 18px 0 8px; }
    p { font-size: 14px; line-height: 1.6; margin-bottom: 10px; color: #444; }
    .summary-box { background: #fdf0f2; border-left: 4px solid #E31937; padding: 14px 18px; border-radius: 4px; margin-bottom: 24px; font-size: 15px; line-height: 1.7; color: #333; }
    .detail-label { font-weight: bold; color: #E31937; }
    table { width: 100%; border-collapse: collapse; margin-top: 6px; font-size: 13px; }
    th { background: #E31937; color: #fff; padding: 7px 10px; text-align: center; }
    td { border: 1px solid #ddd; padding: 7px 10px; text-align: center; }
    td.ear { font-weight: bold; color: #E31937; background: #fff; }
    tr.alt td { background: #fdf0f2; }
    ul { padding-left: 20px; margin-top: 6px; }
    li { font-size: 14px; line-height: 1.7; color: #444; }
    footer { margin-top: 48px; border-top: 1px solid #ddd; padding-top: 12px; font-size: 11px; color: #999; text-align: center; }
    @media print { body { padding: 20px 30px; } }
  </style>
</head>
<body>
  <header>
    <h1>Sonaris</h1>
    <span>Generated on ${date}</span>
  </header>
  <h2>${title}</h2>
  <div class="summary-box">${analysis.summary ?? 'Analysis complete.'}</div>
  ${analysis.explanation ? `<p><span class="detail-label">Explanation:</span> ${analysis.explanation}</p>` : ''}
  ${analysis.whyHearingLoss ? `<p><span class="detail-label">Analysis:</span> ${analysis.whyHearingLoss}</p>` : ''}
  ${analysis.howAnalysis ? `<p><span class="detail-label">How we read it:</span> ${analysis.howAnalysis}</p>` : ''}
  ${thresholdsHtml}
  ${recsHtml}
  <footer>This report was generated by Sonaris and is intended as an informational aid only. It does not replace a professional medical diagnosis.</footer>
</body>
</html>`;
}

export default function HearingLossResultsScreen() {
  const router = useRouter();
  const [showDetails, setShowDetails] = useState(false);
  const [pdfLoading, setPdfLoading] = useState(false);
  const [analysis] = useState<AnalysisData | null>(() => {
    const data = getAnalysis();
    clearAnalysis();
    return data;
  });

  if (!analysis) {
    return (
      <View style={styles.container}>
        <Text style={styles.errorText}>No analysis data available</Text>
      </View>
    );
  }

  // Determine icon component based on severity
  const getSeverityIcon = (severity: string) => {
    switch (severity?.toLowerCase()) {
      case 'normal':
      case 'mild':
      case 'moderate':
        return <NormalHearing size={200} />;
      case 'moderately_severe':
      case 'moderately severe':
      case 'severe':
      case 'profound':
      default:
        return <SevereHearing size={200} />;
    }
  };

  const handleDownloadPdf = async () => {
    if (!analysis) return;
    const title = getSeverityTitle(analysis.severity);
    const html = buildPdfHtml(analysis, title);
    setPdfLoading(true);
    try {
      if (Platform.OS === 'web') {
        await Print.printAsync({ html });
      } else {
        const { uri } = await Print.printToFileAsync({ html });
        if (await Sharing.isAvailableAsync()) {
          await Sharing.shareAsync(uri, { mimeType: 'application/pdf', dialogTitle: 'Save or share your report' });
        } else {
          Alert.alert('Saved', `PDF saved to: ${uri}`);
        }
      }
    } catch {
      Alert.alert('Error', 'Could not generate PDF. Please try again.');
    } finally {
      setPdfLoading(false);
    }
  };

  const getSeverityTitle = (severity: string) => {
    switch (severity?.toLowerCase()) {
      case 'normal':
        return 'Normal hearing';
      case 'mild':
        return 'Mild hearing loss';
      case 'moderate':
        return 'Moderate hearing loss';
      case 'moderately_severe':
      case 'moderately severe':
        return 'Moderately severe hearing loss';
      case 'severe':
        return 'Severe hearing loss';
      case 'profound':
        return 'Profound hearing loss';
      default:
        return 'Hearing loss';
    }
  };

  return (
    <ScrollView style={styles.container}>
      <View style={styles.content}>
        <Text style={styles.title}>
          {getSeverityTitle(analysis.severity)}
        </Text>

        <View style={styles.iconContainer}>
          {getSeverityIcon(analysis.severity)}
        </View>

        <View style={styles.resultBox}>
          <Text style={styles.resultText}>
            {analysis.summary || 'Analysis of your audiogram is complete.'}
          </Text>
        </View>

        {showDetails && (
          <View style={styles.detailsBox}>
            {analysis.explanation && (
              <Text style={styles.detailsText}>
                <Text style={styles.detailsLabel}>Explanation: </Text>
                {analysis.explanation}
              </Text>
            )}
            {analysis.whyHearingLoss && (
              <Text style={styles.detailsText}>
                <Text style={styles.detailsLabel}>Analysis: </Text>
                {analysis.whyHearingLoss}
              </Text>
            )}
            {analysis.howAnalysis && (
              <Text style={styles.detailsText}>
                <Text style={styles.detailsLabel}>How we read it: </Text>
                {analysis.howAnalysis}
              </Text>
            )}
            {analysis.thresholds && (
              <View style={styles.thresholdsBox}>
                <Text style={styles.detailsLabel}>Thresholds (dB HL):</Text>
                {/* Header row */}
                {(() => {
                  const thresholds = analysis.thresholds as { leftEar?: Record<string,number>; rightEar?: Record<string,number> };
                  const freqs = ['250','500','1k','2k','4k','8k'];
                  const freqKeys = ['250','500','1000','2000','4000','8000'];
                  return (
                    <View style={styles.thresholdTable}>
                      <View style={styles.thresholdRow}>
                        <Text style={styles.thresholdLabelCell}>Hz</Text>
                        {freqs.map(f => (
                          <Text key={f} style={styles.thresholdHeaderCell}>{f}</Text>
                        ))}
                      </View>
                      {thresholds.leftEar && (
                        <View style={styles.thresholdRow}>
                          <Text style={styles.thresholdEarCell}>L</Text>
                          {freqKeys.map(f => (
                            <Text key={f} style={styles.thresholdValueCell}>
                              {thresholds.leftEar![f] ?? '—'}
                            </Text>
                          ))}
                        </View>
                      )}
                      {thresholds.rightEar && (
                        <View style={[styles.thresholdRow, styles.thresholdRowAlt]}>
                          <Text style={styles.thresholdEarCell}>R</Text>
                          {freqKeys.map(f => (
                            <Text key={f} style={styles.thresholdValueCell}>
                              {thresholds.rightEar![f] ?? '—'}
                            </Text>
                          ))}
                        </View>
                      )}
                    </View>
                  );
                })()}
              </View>
            )}
            {analysis.recommendations && analysis.recommendations.length > 0 && (
              <View style={styles.recommendationsBox}>
                <Text style={styles.detailsLabel}>Recommendations:</Text>
                {analysis.recommendations.map((rec: string, index: number) => (
                  <Text key={index} style={styles.recommendationItem}>
                    • {rec}
                  </Text>
                ))}
              </View>
            )}
            {/* Fallback: show any extra fields the AI returned that aren't displayed above */}
            {(() => {
              const knownKeys = new Set(['hearingLossDetected', 'severity', 'summary', 'explanation', 'whyHearingLoss', 'howAnalysis', 'thresholds', 'recommendations']);
              const extraEntries = Object.entries(analysis).filter(([k, v]) => {
                if (knownKeys.has(k)) return false;
                if (v === null || v === undefined) return false;
                if (Array.isArray(v) && v.length === 0) return false;
                if (typeof v === 'object' && !Array.isArray(v) && Object.keys(v as object).length === 0) return false;
                return true;
              });
              if (extraEntries.length === 0) return null;
              return (
                <View>
                  {extraEntries.map(([key, value]) => (
                    <Text key={key} style={styles.detailsText}>
                      <Text style={styles.detailsLabel}>{key}: </Text>
                      {typeof value === 'string' ? value : JSON.stringify(value)}
                    </Text>
                  ))}
                </View>
              );
            })()}
            {/* If absolutely nothing rendered, show a message */}
            {!analysis.explanation && !analysis.whyHearingLoss && !analysis.howAnalysis && !analysis.thresholds && !(analysis.recommendations?.length) &&
              Object.keys(analysis).filter(k => !['hearingLossDetected','severity','summary'].includes(k)).length === 0 && (
              <Text style={styles.detailsText}>No additional details available.</Text>
            )}
          </View>
        )}

        <Pressable 
          style={styles.readMoreButton}
          onPress={() => setShowDetails(!showDetails)}
        >
          <Text style={styles.readMoreText}>
            {showDetails ? 'Show less' : 'Show more'}
          </Text>
        </Pressable>
      </View>

      <View style={styles.buttonContainer}>
        <Pressable style={[styles.scanButton, pdfLoading && styles.buttonDisabled]} onPress={handleDownloadPdf} disabled={pdfLoading}>
          <Text style={styles.scanButtonText}>{pdfLoading ? 'Generating…' : 'Download PDF'}</Text>
        </Pressable>
        <Pressable style={styles.pdfButton} onPress={() => router.push('/upload-audiogram')}>
          <Text style={styles.pdfButtonText}>Scan new audiogram</Text>
        </Pressable>
      </View>
    </ScrollView>
  );
}

